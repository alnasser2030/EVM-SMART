// Typeset the film's equations to standalone SVG with MathJax, saved as equations.js.
// One-time setup (outside the repo is fine):  npm install mathjax-full@3.2.2
// Usage:  NODE_PATH=<dir>/node_modules node media/prelim_film/build_equations.js
const fs = require('fs');
const path = require('path');
const { mathjax } = require('mathjax-full/js/mathjax.js');
const { TeX } = require('mathjax-full/js/input/tex.js');
const { SVG } = require('mathjax-full/js/output/svg.js');
const { liteAdaptor } = require('mathjax-full/js/adaptors/liteAdaptor.js');
const { RegisterHTMLHandler } = require('mathjax-full/js/handlers/html.js');
const { AllPackages } = require('mathjax-full/js/input/tex/AllPackages.js');

const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const doc = mathjax.document('', {
  InputJax: new TeX({ packages: AllPackages }),
  OutputJax: new SVG({ fontCache: 'none' }),
});

const EQ = {
  cfe: String.raw`\mathrm{CFE}=\dfrac{\sum_t \min(L_t,P_t)\;+\;\sum_t d_t}{\sum_t L_t}`,
  net: String.raw`s_t=[P_t-L_t]^{+},\qquad g_t=[L_t-P_t]^{+}`,
  state: String.raw`S_t=(1-\delta_t)\,S_{t-1}+\eta\,u_t-d_t`,
  bounds: String.raw`0\le u_t\le \min(P^F,s_t),\qquad 0\le d_t\le \min(P^F,g_t)`,
  energy: String.raw`0\le S_t\le D\,P^F,\qquad S_t=0\ \ \forall t\in\mathcal{E}`,
  obj: String.raw`\min\ P^F\quad \text{s.t.}\quad \sum_t d_t\;\ge\; X\sum_t L_t-\sum_t \min(L_t,P_t)`,
  bess: String.raw`Q_t=Q_{t-1}+\eta_c\,c_t-b_t/\eta_d,\qquad 0\le Q_t\le E`,
  pi: String.raw`\pi^{\ast}(X)=\dfrac{C^B(X)}{\sum_t d_t(X)}`,
};

const out = {};
for (const [k, tex] of Object.entries(EQ)) {
  const node = doc.convert(tex, { display: true });
  const svg = adaptor.innerHTML(node);
  const vb = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  out[k] = { svg, vb };
}
const file = path.join(__dirname, 'equations.js');
fs.writeFileSync(file, '// Generated by build_equations.js (MathJax 3.2.2). Do not edit by hand.\nwindow.EQ = ' + JSON.stringify(out) + ';\n');
console.log('wrote', file, Object.keys(out).length, 'equations');
